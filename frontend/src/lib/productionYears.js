/**
 * Get production year range for make/model (Thailand). Normalizes make (MERCEDES-BENZ → BENZ).
 * @param {string} make - Make (e.g. BENZ, AUDI)
 * @param {string} model - Model (e.g. A-CLASS, A4)
 * @returns {{ start: number, end: number } | null} Start/end year or null if no rule
 */
export function getProductionRange(make, model) {
  if (!make || !model) return null;
  const makeKey = String(make).trim().toUpperCase();
  const modelKey = String(model).trim().toUpperCase();
  const byModel = BY_MAKE[makeKey] || BY_MAKE[makeKey === 'MERCEDES-BENZ' ? 'BENZ' : makeKey];
  if (!byModel) return null;
  return byModel[modelKey] || null;
}

