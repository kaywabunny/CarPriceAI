export const getTranslation = (key, lang = 'en', params = {}) => {
  const translation = translations[lang]?.[key] || translations.en[key] || key;
  const str = typeof translation === 'string' ? translation : String(key ?? '');
  // Replace parameters like {url}
  return str.replace(/\{(\w+)\}/g, (match, paramKey) => {
    return params[paramKey] != null ? String(params[paramKey]) : match;
  });
};

